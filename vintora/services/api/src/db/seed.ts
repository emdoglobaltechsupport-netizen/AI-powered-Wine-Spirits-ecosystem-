import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { config } from '../config.js';
import { hashPassword } from '../lib/password.js';
import { migrate } from './migrate.js';
import { pool } from './pool.js';
import { TENANT_ID, tenantQuery } from './tenant.js';

const seedDir = fileURLToPath(new URL('../../../../packages/db/seed/', import.meta.url));
const credentialPolicyPath = fileURLToPath(new URL('../../../../config/credential-policy.json', import.meta.url));

interface CredentialPolicy {
  localProfiles: string[];
  generatedSeedPasswordPrefix: string;
  legacyPasswordPatterns: string[];
}

async function loadCredentialPolicy(): Promise<CredentialPolicy> {
  return JSON.parse(await readFile(credentialPolicyPath, 'utf8')) as CredentialPolicy;
}

function matchesAny(value: string | undefined, patterns: string[]): boolean {
  return typeof value === 'string' && patterns.some((pattern) => new RegExp(pattern, 'i').test(value));
}

async function runSqlFile(filename: string, replacements: Record<string, string> = {}): Promise<void> {
  let raw = await readFile(`${seedDir}${filename}`, 'utf8');
  for (const [token, value] of Object.entries(replacements)) {
    raw = raw.split(`{{${token}}}`).join(value);
  }
  const sql = raw.replace(/^\s*BEGIN;\s*$/gim, '').replace(/^\s*COMMIT;\s*$/gim, '');
  await pool.query(sql);
}

async function ensureUser(email: string, displayName: string, password: string): Promise<string> {
  const hash = await hashPassword(password);
  const rows = await tenantQuery<{ id: string }>(
    `INSERT INTO users (email, display_name, locale, preferred_currency, country_code,
                        status, password_hash, tenant_id, access_jurisdictions)
     VALUES ($1, $2, 'en', 'USD', 'US', 'active', $3, $4, $5::text[])
     ON CONFLICT (email) DO UPDATE
       SET password_hash = EXCLUDED.password_hash,
           display_name = EXCLUDED.display_name,
           updated_at = now()
     RETURNING id`,
    [email, displayName, hash, TENANT_ID, ['US', 'GB']],
    TENANT_ID,
  );
  const id = rows[0]?.id;
  if (!id) throw new Error(`Could not create user ${email}`);
  return id;
}

/** Apply migrations and reference/demo catalogue data. No identities are created here. */
export async function seedDatabase(): Promise<void> {
  const result = await migrate();
  console.log(`[db] migrations: ${result.applied.length} applied, ${result.skipped} already current`);
  console.log(`[db] recorded embedding mode: ${result.embeddingMode}`);
  if (result.applied.length) console.log(`[db] applied: ${result.applied.join(', ')}`);

  await runSqlFile('001_seed.sql');
  await runSqlFile('003_product_content.sql');
  console.log('[db] seeded reference data and source-labelled demo catalogue');
}

/**
 * Development-only identity seed. This path is explicit, profile-gated and
 * never part of the migrations-only `db:setup` command.
 */
export async function seedDevIdentities(): Promise<void> {
  if (config.isProduction) {
    throw new Error('Demo identity seeding is disabled in production');
  }
  const demoSeedProfiles = new Set(['local', 'test']);
  if (!demoSeedProfiles.has(config.runtimeBoundary.profile ?? '')) {
    throw new Error('Demo identity seeding is only allowed in local or test runtime profiles');
  }
  if (config.ALLOW_DEMO_SEED !== 'true') {
    throw new Error('Demo identity seeding requires ALLOW_DEMO_SEED=true');
  }

  const policy = await loadCredentialPolicy();
  for (const password of [config.SEED_ADMIN_PASSWORD, config.SEED_USER_PASSWORD]) {
    if (matchesAny(password, policy.legacyPasswordPatterns)) {
      throw new Error('Fixed demo credentials are not permitted; regenerate with npm run setup:env -- --force');
    }
    if (!password.startsWith(policy.generatedSeedPasswordPrefix)) {
      throw new Error('Seeded demo passwords must be generated by npm run setup:env');
    }
  }
  if (!policy.localProfiles.includes(String(config.runtimeBoundary.profile))) {
    throw new Error('Demo identity seeding is only allowed in local or test runtime profiles');
  }

  await seedDatabase();

  const adminId = await ensureUser(
    config.SEED_ADMIN_EMAIL, 'Vintora Admin', config.SEED_ADMIN_PASSWORD,
  );
  await ensureUser(config.SEED_USER_EMAIL, 'Demo Collector', config.SEED_USER_PASSWORD);
  await ensureUser('business@vintora.local', 'Demo Distributor', config.SEED_USER_PASSWORD);
  await ensureUser('seller@vintora.local', 'Demo Merchant', config.SEED_USER_PASSWORD);

  // Named approvers for four-eyes actions. They are ordinary users, not admins.
  for (const code of ['finance_ops', 'seller_ops', 'ai_ops', 'growth_ops', 'auditor']) {
    await ensureUser(`${code}@vintora.local`, code, config.SEED_USER_PASSWORD);
  }

  const replacements = {
    ADMIN_EMAIL: config.SEED_ADMIN_EMAIL,
    USER_EMAIL: config.SEED_USER_EMAIL,
  };
  await runSqlFile('002_app_seed.sql', replacements);
  await runSqlFile('004_admin_domain_seed.sql', replacements);
  await runSqlFile('005_identity_access_seed.sql');
  console.log(`[db] seeded local-only demo identities (admin=${adminId}); not valid outside local/test`);
}
